--[[
  Convert a Polyglot .bin opening book into Lua tables.
  Not loaded by the TOC; used by the CLI and tests.

  Record layout (16 bytes, big-endian):
    key    uint64
    move   uint16  (to 0-5, from 6-11, promo 12-14; 1=n 2=b 3=r 4=q)
    weight uint16
    learn  uint32  (ignored)

  Castling in Polyglot is king-takes-rook (e1h1); this module emits king-moves (e1g1).
  Entries with weight 0 are dropped.
]]

local M = {}

local FILES = "abcdefgh"
local PROMO = { [1] = "n", [2] = "b", [3] = "r", [4] = "q" }

local function sqToUci(sq)
  local f = sq % 8
  local r = math.floor(sq / 8)
  return FILES:sub(f + 1, f + 1) .. tostring(r + 1)
end

local function hex8(n)
  local hi = math.floor((n % 4294967296) / 65536)
  local lo = n % 65536
  return string.format("%04x%04x", hi, lo)
end

--- Decode a Polyglot move word to UCI (castling as king destination, e.g. e1g1).
function M.DecodeMove(raw)
  raw = tonumber(raw) or 0
  local to = raw % 64
  local from = math.floor(raw / 64) % 64
  local promo = math.floor(raw / 4096) % 8

  -- Polyglot encodes castling as king takes own rook.
  if from == 4 and to == 7 then
    to = 6
  elseif from == 4 and to == 0 then
    to = 2
  elseif from == 60 and to == 63 then
    to = 62
  elseif from == 60 and to == 56 then
    to = 58
  end

  local uci = sqToUci(from) .. sqToUci(to)
  local promoChar = PROMO[promo]
  if promoChar then
    uci = uci .. promoChar
  end
  return uci
end

local function readU16be(data, i)
  local b1, b2 = data:byte(i, i + 1)
  if not b2 then return nil end
  return b1 * 256 + b2
end

local function readU32be(data, i)
  local b1, b2, b3, b4 = data:byte(i, i + 3)
  if not b4 then return nil end
  return ((b1 * 256 + b2) * 256 + b3) * 256 + b4
end

local function addMove(list, move, weight)
  for i = 1, #list do
    if list[i].move == move then
      list[i].weight = list[i].weight + weight
      return
    end
  end
  list[#list + 1] = { move = move, weight = weight }
end

--- Parse Polyglot binary data into { [hexKey] = { { move, weight }, ... } }.
function M.ParseRecords(data)
  local entries = {}
  if not data or #data < 16 then
    return entries
  end
  local n = math.floor(#data / 16)
  for rec = 0, n - 1 do
    local i = rec * 16 + 1
    local keyHigh = readU32be(data, i)
    local keyLow = readU32be(data, i + 4)
    local rawMove = readU16be(data, i + 8)
    local weight = readU16be(data, i + 10)
    if weight and weight > 0 and rawMove then
      local key = hex8(keyHigh) .. hex8(keyLow)
      local move = M.DecodeMove(rawMove)
      local list = entries[key]
      if not list then
        list = {}
        entries[key] = list
      end
      addMove(list, move, weight)
    end
  end
  return entries
end

local function luaQuote(s)
  return string.format("%q", s)
end

local function sortedKeys(t)
  local keys = {}
  for k in pairs(t) do
    keys[#keys + 1] = k
  end
  table.sort(keys)
  return keys
end

--- Build a Lua source file that registers the book with LibChessOpeningBook.
-- opts: { id, name, description, elo, entries }
function M.EncodeLua(opts)
  opts = opts or {}
  local id = opts.id or "converted"
  local name = opts.name or id
  local description = opts.description or ""
  local entries = opts.entries or {}

  local lines = {
    "-- Generated by LibChessOpeningBook Polyglot converter.",
    "local Book = LibStub(\"LibChessOpeningBook-1.0\")",
    "Book:Register({",
    "  id = " .. luaQuote(id) .. ",",
    "  name = " .. luaQuote(name) .. ",",
    "  description = " .. luaQuote(description) .. ",",
  }
  if opts.elo then
    if type(opts.elo) == "table" then
      lines[#lines + 1] = string.format("  elo = { %s, %s },", tostring(opts.elo[1]), tostring(opts.elo[2]))
    else
      lines[#lines + 1] = "  elo = " .. tostring(opts.elo) .. ","
    end
  end
  lines[#lines + 1] = "  entries = {"

  local keys = sortedKeys(entries)
  for _, key in ipairs(keys) do
    local moves = entries[key]
    lines[#lines + 1] = "    [" .. luaQuote(key) .. "] = {"
    for i = 1, #moves do
      local m = moves[i]
      lines[#lines + 1] = string.format(
        "      { move = %s, weight = %d },",
        luaQuote(m.move),
        m.weight or 1
      )
    end
    lines[#lines + 1] = "    },"
  end

  lines[#lines + 1] = "  },"
  lines[#lines + 1] = "})"
  lines[#lines + 1] = ""
  return table.concat(lines, "\n")
end

return M
